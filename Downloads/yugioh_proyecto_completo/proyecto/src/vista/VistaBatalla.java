// ---- Batalla ----
public int getIndiceAtacante() { return cmbAtacante.getSelectedIndex(); }          // 0 = J1 ataca, 1 = J2 ataca

public int getIndiceSeleccionado(int jugador) {
    return (jugador == 0) ? listCampoJ1.getSelectedIndex() : listCampoJ2.getSelectedIndex();
}

public void setNombre(int jugador, String nombre) {
    (jugador == 0 ? lblNombreJ1 : lblNombreJ2).setText(nombre);
}

public void setLp(int jugador, int lp) {
    (jugador == 0 ? lblLpJ1 : lblLpJ2).setText("LP: " + lp);
}

public void setCampo(int jugador, java.util.List<String> items) {
    javax.swing.DefaultListModel<String> modelo = new javax.swing.DefaultListModel<>();
    for (String s : items) {
        modelo.addElement(s);
    }
    (jugador == 0 ? listCampoJ1 : listCampoJ2).setModel(modelo);
}

public void agregarHistorial(String linea) { txtaHistorial.append(linea + "\n"); }

public void setBatallaHabilitada(boolean habilitada) {
    btnInvocar.setEnabled(habilitada);
    btnAtacar.setEnabled(habilitada);
    btnAtaqueDirecto.setEnabled(habilitada);
}

